export const dicts = { en, hi };

type I18nCtx = { lang: Lang; setLang: (l: Lang) => void; t: (k: keyof typeof en) => string };
const Ctx = createContext<I18nCtx>({ lang: "en", setLang: () => {}, t: (k) => String(k) });

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    storage.getItem<Lang>("tm_lang", "en").then((l) => l && setLangState(l));
  }, []);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    storage.setItem("tm_lang", l);
  }, []);
  const t = useCallback((k: keyof typeof en) => dicts[lang][k] ?? String(k), [lang]);
  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}
